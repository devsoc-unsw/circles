// Generates src/validate/generated/validators.js (+ .d.ts): Ajv standalone validators for
// schema.json, so the browser never compiles schemas (no `new Function` under a strict CSP) and
// Ajv itself stays out of the bundle. Usage: npm run build-validators
// Re-run after re-syncing test-data/schema.json; test/validate.test.ts fails while it is stale.
import Ajv2020 from 'ajv/dist/2020.js';
import standaloneCode from 'ajv/dist/standalone/index.js';
import addFormats from 'ajv-formats';
import { createHash } from 'node:crypto';
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const packageDir = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const schemaPath = join(packageDir, 'test-data', 'schema.json');
const outDir = join(packageDir, 'src', 'validate', 'generated');

// Exported validator name → schema ref. Per-kind validators give focused errors (validate.mjs KIND_DEF).
const KIND_DEF: Record<string, string> = {
  program: 'programDoc',
  specialisation: 'specialisationDoc',
  course_conditions: 'courseConditionsDoc',
  patch: 'patchDoc',
  library: 'libraryDoc'
};

const text = readFileSync(schemaPath, 'utf8');
const schema = JSON.parse(text) as { $id: string };
const sha256 = createHash('sha256').update(text).digest('hex');

// Same options as tools/validate.mjs, so error messages match tools/negative/expected.txt.
const ajv = new Ajv2020({
  allErrors: true,
  strict: false,
  inlineRefs: false,
  code: { source: true, esm: true }
});
addFormats(ajv);
ajv.addSchema(schema);

const entries: Record<string, string> = {
  validateDoc: schema.$id,
  validateFixture: `${schema.$id}#/$defs/fixture`
};
for (const [kind, def] of Object.entries(KIND_DEF)) {
  entries[`validate_${kind}`] = `${schema.$id}#/$defs/${def}`;
}

// Ajv emits CommonJS require() for its runtime helpers even in ESM mode; point them at
// src/validate/runtime.ts instead so the generated module has no dependency on Ajv.
const code = standaloneCode(ajv, entries)
  .replaceAll('require("ajv/dist/runtime/ucs2length").default', 'runtime.ucs2length')
  .replace(/require\("ajv-formats\/dist\/formats"\)\.fullFormats\.(\w+)/g, 'runtime.formats.$1');
const leftover = /require\([^)]*\)/.exec(code);
if (leftover) throw new Error(`unhandled runtime import in generated code: ${leftover[0]}`);
mkdirSync(outDir, { recursive: true });
writeFileSync(
  join(outDir, 'validators.js'),
  `// GENERATED by scripts/build-validators.ts from test-data/schema.json. Do not edit.
// schema sha256: ${sha256}
/* eslint-disable */
import * as runtime from '../runtime';
${code}
`
);

const names = Object.keys(entries).sort();
writeFileSync(
  join(outDir, 'validators.d.ts'),
  `// GENERATED by scripts/build-validators.ts. Do not edit.
export interface SchemaError {
  instancePath: string;
  keyword: string;
  message?: string;
  params: Record<string, unknown>;
}
export type Validator = ((data: unknown) => boolean) & { errors?: SchemaError[] | null };
${names.map((n) => `export declare const ${n}: Validator;`).join('\n')}
export declare const SCHEMA_SHA256: string;
`
);
writeFileSync(
  join(outDir, 'validators.js'),
  `${readFileSync(join(outDir, 'validators.js'), 'utf8')}export const SCHEMA_SHA256 = '${sha256}';\n`
);
console.log(`build-validators: ${names.join(', ')} (schema ${sha256.slice(0, 12)})`);
